"""The schema of a store database on PostgreSQL (nixidae/nixidae#1209): Nix's tables and pynixd's.

pynixd is the only program that writes such a database, so pynixd creates Nix's tables too. They
take the shape of a Nix 2.35 store with `ca-derivations` and Determinate Nix's `provenance`
(`create_store.SCHEMA`, `CA_SCHEMA`, `PROVENANCE_COLUMN`): the shape pynixd's statements of Nix read.
pynixd's tables start at the end state of `db_migrations.MIGRATIONS`, version `BASE_VERSION`. A
migration after it gets a twin here under the same version.

No program but pynixd reads these tables, so a list or a flag that Nix packs into text or an
integer has a native type here (`text[]`, `boolean`), and `sql.codec` binds it. `ValidPaths.hash`
is the 32 bytes of the SHA-256 digest: every write of Nix's is SHA-256 (`local-store.cc:975`),
so the `sha256:` and the base-16 text carry nothing. Each rule below
keeps the behaviour of the other columns the same as in SQLite:

- Every text column is `COLLATE "C"`. SQLite compares text bytewise (`BINARY`), and a range scan
  over store paths relies on that order.
- Every integer column is `BIGINT`. SQLite stores up to 64 bits in any `INTEGER` column, and a NAR
  size or a time in milliseconds does not fit in 32.
- An `INTEGER PRIMARY KEY` is an identity column: SQLite gives a row its id when an insert names none.

`test_postgres_schema.py` compares the tables and columns of both engines.
"""

